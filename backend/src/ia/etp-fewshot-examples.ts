/**
 * Retorna os exemplos few-shot formatados para inserção no system prompt.
 * Limita a quantidade para não ultrapassar o contexto do modelo.
 */
export function getEtpFewShotContext(dominioKeywords: string[]): string {
  const lower = dominioKeywords.join(' ').toLowerCase();

  // Seleciona o exemplo mais relevante + 1 de domínio diferente para variedade
  const isEngenharia = /engenhar|obra|reform|construç|banheiro|predial|hidráulic|elétric|paviment|pintura|demoliç|revestim/.test(lower);
  const isTI = /software|licença|sistema|ti |tecnologia|servidor|computador|rede|backup|antivír|cloud/.test(lower);
  const isLimpeza = /limpeza|conserv|higieniz|asseio|zeladori|portaria|copeira|vigilânc|segurança patrimon/.test(lower);
  const isMobiliario = /mobiliário|móveis|cadeira|mesa|armário|estante|equip/.test(lower);
  const isVeiculo = /veícul|frota|carro|ônibus|van|caminhão|automóvel|sedan/.test(lower);
  const isMedicamento = /medicamento|farmacêutic|remédio|insumo|saúde|médico|hospitalar/.test(lower);

  let exemplos = '';

  if (isEngenharia) {
    exemplos += ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO 2')[0]; // Só o exemplo 1
  } else if (isTI) {
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[3]; // Exemplo 3 (TI)
    exemplos = exemplos.split('=== EXEMPLO 4')[0];
  } else if (isLimpeza) {
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[2]; // Exemplo 2 (Limpeza)
    exemplos = exemplos.split('=== EXEMPLO 3')[0];
  } else if (isMobiliario) {
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[4]; // Exemplo 4 (Mobiliário)
    exemplos = exemplos.split('=== EXEMPLO 5')[0];
  } else if (isVeiculo) {
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[6]; // Exemplo 6 (Veículos)
    exemplos = exemplos.split('=== EXEMPLO 7')[0];
  } else if (isMedicamento) {
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[7]; // Exemplo 7 (Saúde)
  } else {
    // Genérico: usa o de limpeza (mais universal)
    const partes = ETP_FEWSHOT_EXAMPLES.split('=== EXEMPLO ');
    exemplos += '=== EXEMPLO ' + partes[2];
    exemplos = exemplos.split('=== EXEMPLO 3')[0];
  }

  return exemplos.trim();
}
